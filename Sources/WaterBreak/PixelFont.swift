    /// Pixel offsets (column, row) that are lit for the given text, laid out
    /// left to right with `spacing` blank columns between glyphs.
    static func pixels(for text: String, spacing: Int = 1) -> [(x: Int, y: Int)] {
        var result: [(x: Int, y: Int)] = []
        var cursor = 0
        for character in text.uppercased() {
            let rows = glyphs[character] ?? glyphs[" "]!
            for (rowIndex, row) in rows.enumerated() {
                for (columnIndex, cell) in row.enumerated() where cell == "#" {
                    result.append((x: cursor + columnIndex, y: rowIndex))
                }
            }
            cursor += glyphWidth + spacing
        }
        return result
    }

    /// Width in font pixels that `text` occupies once laid out.
    static func width(of text: String, spacing: Int = 1) -> Int {
        guard !text.isEmpty else { return 0 }
        return text.count * (glyphWidth + spacing) - spacing
    }
}
